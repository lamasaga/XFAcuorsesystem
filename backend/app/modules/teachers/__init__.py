# ========================================
# 教师管理模块
# ========================================
#
# 这个模块负责教师数据的管理，包括：
#   - 教师信息的增删改查
#   - 教师类型（中教/外教）
#   - 教师学部（小学部/中学部）
#   - 教师标签（班主任、管理干部等）
#   - 教师任教科目
#
# 文件说明：
#   - models.py: 教师表的数据库模型
#   - schemas.py: 教师数据的验证模式
#   - crud.py: 教师数据的数据库操作
#   - router.py: 教师管理的 API 接口
# ========================================
